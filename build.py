"""Build site/data.js from data/*.yaml.

Applies data/policy.yaml: tools missing a required criterion are dropped with
a warning. Presets referencing unknown or dropped tools are also warned about.
"""
import glob
import hashlib
import json
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "site", "data.js")
INDEX = os.path.join(ROOT, "site", "index.html")
# Assets referenced from index.html that get a content-hash query string so
# browsers fetch a new copy after a deploy. The server sends a ten-year
# max-age for static files, so a bare "data.js" would stay stale.
STAMPED = ["style.css", "app.js", "data.js"]


def load(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def stamp_assets():
    """Rewrite href/src of STAMPED assets in index.html to name?v=<hash>."""
    with open(INDEX, encoding="utf-8") as f:
        html = f.read()
    for name in STAMPED:
        with open(os.path.join(ROOT, "site", name), "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()[:10]
        html = re.sub(
            r'((?:href|src)=")%s(?:\?v=[0-9a-f]+)?"' % re.escape(name),
            r'\g<1>%s?v=%s"' % (name, digest),
            html,
        )
    with open(INDEX, "w", encoding="utf-8") as f:
        f.write(html)


def main():
    criteria = load(os.path.join(DATA, "criteria.yaml"))
    categories = load(os.path.join(DATA, "categories.yaml"))
    policy = load(os.path.join(DATA, "policy.yaml")) or {}
    presets = load(os.path.join(DATA, "presets.yaml"))

    crit_ids = {c["id"] for c in criteria}
    cat_by_id = {c["id"]: c for c in categories}
    required = set(policy.get("required") or [])
    any_of = [list(g) for g in (policy.get("any_of") or [])]

    tools = []
    for path in sorted(glob.glob(os.path.join(DATA, "tools", "*.yaml"))):
        tools.extend(load(path) or [])

    seen = set()
    admitted = []
    warnings = []
    for t in tools:
        tid = t["id"]
        if tid in seen:
            warnings.append(f"duplicate tool id: {tid}")
            continue
        seen.add(tid)
        cat = cat_by_id.get(t["category"])
        if cat is None:
            warnings.append(f"{tid}: unknown category {t['category']}")
            continue
        unknown = set(t.get("criteria", [])) - crit_ids
        if unknown:
            warnings.append(f"{tid}: unknown criteria {sorted(unknown)}")
        waived = set(cat.get("waive", []))
        have = set(t.get("criteria", []))
        need = (required - waived) | set(cat.get("require", []))
        missing = need - have
        if missing:
            warnings.append(f"{tid}: dropped, missing required {sorted(missing)}")
            continue
        failed_group = None
        for group in any_of:
            # Waiving any member of a group waives the whole group: the
            # category has decided that this requirement does not apply.
            if waived.intersection(group):
                continue
            if not have.intersection(group):
                failed_group = group
                break
        if failed_group:
            warnings.append(f"{tid}: dropped, needs one of {failed_group}")
            continue
        admitted.append(t)

    tool_ids = {t["id"] for t in admitted}
    for p in presets:
        for cat_id, picks in p["picks"].items():
            if cat_id not in cat_by_id:
                warnings.append(f"preset {p['id']}: unknown category {cat_id}")
            for pick in picks:
                if pick not in tool_ids:
                    warnings.append(f"preset {p['id']}: unknown or dropped tool {pick}")

    payload = {
        "criteria": criteria,
        "categories": categories,
        "policy": policy,
        "presets": presets,
        "tools": admitted,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py. Do not edit; edit data/*.yaml instead.\n")
        f.write("// SPDX-License-Identifier: CC-BY-SA-4.0 (pool data), see data/LICENSE\n")
        f.write("// Copyright (C) 2026 schmidt1024 and contributors\n")
        f.write("window.STACK_DATA = ")
        json.dump(payload, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    stamp_assets()

    for w in warnings:
        print("warn:", w, file=sys.stderr)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(admitted)} tools, "
          f"{len(categories)} categories, {len(presets)} presets")
    return 1 if any(w.endswith("]") and "dropped" in w for w in warnings) else 0


if __name__ == "__main__":
    sys.exit(main())
